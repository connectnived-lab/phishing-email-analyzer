"""Copy the shared rule data and the sample emails into the web demo.

Run after changing src/phishcheck/data/rules.json or anything in samples/:

    python scripts/build_web.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "src" / "phishcheck" / "data" / "rules.json"
WEB_JS = ROOT / "web" / "js"

LABELS = {
    "01_sbi_kyc_update.eml": "SBI KYC scam",
    "02_microsoft365_password_expiry.eml": "Microsoft 365 password",
    "03_paytm_lottery.eml": "Paytm lottery",
    "04_amazon_invoice_attachment.eml": "Fake Amazon invoice (.exe)",
    "05_hdfc_ip_link.eml": "HDFC IP-address link",
    "06_salary_revision_macro.eml": "Salary file with macros",
    "01_github_security_alert.eml": "GitHub security alert",
    "02_hdfc_statement.eml": "HDFC statement",
    "03_colleague_meeting.eml": "Colleague meeting",
    "04_amazon_order_shipped.eml": "Amazon order shipped",
    "05_microsoft_signin_notice.eml": "Microsoft security notice",
    "06_flipkart_sale_newsletter.eml": "Flipkart newsletter",
}


def main() -> None:
    rules = json.loads(RULES.read_text(encoding="utf-8"))
    (WEB_JS / "rules.js").write_text(
        "// Generated by scripts/build_web.py from src/phishcheck/data/rules.json. Do not edit.\n"
        "globalThis.PHISHCHECK_RULES = " + json.dumps(rules, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    samples = []
    for kind in ("phishing", "legit"):
        for path in sorted((ROOT / "samples" / kind).glob("*.eml")):
            samples.append({
                "id": path.stem,
                "kind": kind,
                "label": LABELS.get(path.name, path.stem),
                "raw": path.read_text(encoding="utf-8"),
            })
    (WEB_JS / "samples.js").write_text(
        "// Generated by scripts/build_web.py from samples/. Do not edit.\n"
        "globalThis.PHISHCHECK_SAMPLES = " + json.dumps(samples, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote rules.js and samples.js ({len(samples)} samples)")


if __name__ == "__main__":
    main()
